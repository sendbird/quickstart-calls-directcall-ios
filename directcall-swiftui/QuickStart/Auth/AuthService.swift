import Foundation
import Observation
import SendBirdCalls

/// Signs in to and out of Sendbird Calls, and publishes the signed-in state to SwiftUI views.
@MainActor
@Observable
final class AuthService {
    static let shared = AuthService()

    /// The stored credential. It is set before auto sign-in finishes so that the main screen shows right away,
    /// and is cleared when auto sign-in fails.
    private(set) var currentCredential: Credential?
    var isSignedIn: Bool { currentCredential != nil }

    private let store: CredentialStore

    init(store: CredentialStore = CredentialStore()) {
        self.store = store
        self.currentCredential = store.credential
    }

    /// Signs in again with the stored credential when the app launches.
    func autoSignIn() async throws {
        guard let credential = store.credential else { throw CredentialError.empty }
        do {
            try await authenticate(with: credential)
        } catch {
            signOutLocally()
            throw error
        }
    }

    /// Signs in with the stored credential only when Sendbird Calls has no signed-in user,
    /// for example when a VoIP push launched the app and the user answers on the CallKit screen.
    func authenticateIfNeeded() async throws {
        guard SendBirdCall.currentUser == nil else { return }
        guard let credential = store.credential else { throw CredentialError.empty }
        try await authenticate(with: credential)
    }

    func signIn(_ credential: Credential) async throws {
        do {
            try await authenticate(with: credential)
        } catch {
            signOutLocally()
            throw error
        }
        // To receive incoming calls, register the VoIP push token for the signed-in user.
        try? await registerVoIPPush(token: store.voipPushToken)
    }

    /// Signs in with `sendbird://<base64 encoded JSON>` opened from outside the app.
    func signIn(url: URL) async throws {
        guard !isSignedIn else { throw CredentialError.alreadyAuthenticated }
        try await signIn(Credential.decode(url: url))
    }

    /// Signs in with the base64 encoded string in a QR code generated by Calls studio.
    func signIn(qrString: String) async throws {
        // Calls studio also shows a QR code that only links to this app's download page.
        guard qrString != "https://dashboard.sendbird.com/calls/mobile" else { throw CredentialError.appDownloadQRCode }
        guard let data = Data(base64Encoded: qrString) else { throw CredentialError.invalidQRCode }
        try await signIn(Credential.decode(qrData: data))
    }

    func signOut() async throws {
        if let token = store.voipPushToken {
            // Stop receiving incoming calls on this device for the signed-in user.
            try? await withCheckedThrowingContinuation { (continuation: CheckedContinuation<Void, Error>) in
                SendBirdCall.unregisterVoIPPush(token: token) { error in
                    if let error { continuation.resume(throwing: error) } else { continuation.resume() }
                }
            }
        }
        try await withCheckedThrowingContinuation { (continuation: CheckedContinuation<Void, Error>) in
            SendBirdCall.deauthenticate { error in
                if let error { continuation.resume(throwing: error) } else { continuation.resume() }
            }
        }
        signOutLocally()
    }

    // MARK: - Sendbird Calls

    private func authenticate(with credential: Credential) async throws {
        // An app can use only one Sendbird application at a time. Configure it again when it differs.
        if SendBirdCall.appId != credential.appId {
            SendBirdCall.configure(appId: credential.appId)
        }

        let params = AuthenticateParams(userId: credential.userId, accessToken: credential.accessToken)
        let user = try await withCheckedThrowingContinuation { (continuation: CheckedContinuation<User, Error>) in
            SendBirdCall.authenticate(with: params) { user, error in
                if let user {
                    continuation.resume(returning: user)
                } else {
                    continuation.resume(throwing: error ?? CredentialError.unknown)
                }
            }
        }

        let signedIn = Credential(
            appId: credential.appId,
            userId: user.userId,
            accessToken: credential.accessToken,
            nickname: user.nickname,
            profileURL: user.profileURL
        )
        store.credential = signedIn
        currentCredential = signedIn
    }

    private func registerVoIPPush(token: Data?) async throws {
        guard let token else { return }
        try await withCheckedThrowingContinuation { (continuation: CheckedContinuation<Void, Error>) in
            SendBirdCall.registerVoIPPush(token: token, unique: false) { error in
                if let error { continuation.resume(throwing: error) } else { continuation.resume() }
            }
        }
    }

    private func signOutLocally() {
        store.clear()
        // The call history belongs to the signed-out user.
        CallHistoryStore.shared.clear()
        currentCredential = nil
    }
}
