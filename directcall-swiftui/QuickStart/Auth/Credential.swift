import Foundation

/// The information needed to sign in to Sendbird Calls.
struct Credential: Codable, Equatable {
    let appId: String
    let userId: String
    let accessToken: String?
    var nickname: String?
    var profileURL: String?

    init(appId: String, userId: String, accessToken: String?, nickname: String? = nil, profileURL: String? = nil) {
        self.appId = appId
        self.userId = userId
        self.accessToken = accessToken
        self.nickname = nickname
        self.profileURL = profileURL
    }
}

enum CredentialError: Error, LocalizedError, Equatable {
    case empty
    case invalidURL
    case invalidQRCode
    case appDownloadQRCode
    case alreadyAuthenticated
    case unknown

    var errorDescription: String? {
        switch self {
        case .empty: return "There is no stored credential."
        case .invalidURL: return "Invalid URL."
        case .invalidQRCode: return "Invalid QR code. Generate a user-specific QR code in Calls studio and try again."
        case .appDownloadQRCode:
            return "This QR code is a link to download the mobile quickstart app, which is already installed on your device. To sign in to this app, generate and scan a user-specific QR code in Calls studio."
        case .alreadyAuthenticated: return "Couldn’t sign you in. If you’re already using the app, sign out first."
        case .unknown: return "Something went wrong. Try again."
        }
    }
}

// MARK: - Decoding a credential from a URL scheme or a QR code
extension Credential {
    /// The URL scheme registered in Info.plist. A URL looks like `sendbird://<base64 encoded JSON>`.
    static let urlScheme = "sendbird://"

    /// Decodes `sendbird://<base64 encoded JSON>`.
    static func decode(url: URL) throws -> Credential {
        let base64String = url.absoluteString.replacingOccurrences(of: urlScheme, with: "")
        guard let data = Data(base64Encoded: base64String) else { throw CredentialError.invalidURL }
        return try decode(qrData: data)
    }

    /// Decodes the JSON in a QR code generated by Calls studio, such as `{"app_id": ..., "user_id": ..., "access_token": ...}`.
    static func decode(qrData: Data) throws -> Credential {
        let decoder = JSONDecoder()
        decoder.keyDecodingStrategy = .convertFromSnakeCase
        return try decoder.decode(Credential.self, from: qrData)
    }
}
